package com.sayists.shyware

import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import java.util.ArrayDeque

/** Fixed-slot transport. Requires an actual network closure and a foreground
 * session scope; the receiver filters dummies before ledger processing.
 * Does not establish transcript unlinkability or hide headers/response timing.
 */
class CoverTrafficAdapter(
    ratePerMinute: Double = 10.0,
    private val scope: CoroutineScope,
    private val transport: suspend (ByteArray) -> ByteArray,
) {
    private data class Pending(val bytes: ByteArray, val result: CompletableDeferred<ByteArray>)
    private val lock = Any()
    private val queue = ArrayDeque<Pending>()
    private var schedule: Job? = null
    private val intervalMillis: Long

    init {
        require(ratePerMinute.isFinite() && ratePerMinute in 0.01..600.0) { "Invalid cover traffic rate" }
        intervalMillis = (60000 / ratePerMinute).toLong()
    }

    companion object {
        const val ENVELOPE_BYTES = 32768
        fun encode(kind: String, body: JsonElement): ByteArray {
            require(kind in setOf("dummy", "cast", "update")) { "Invalid dispatch kind" }
            val bytes = buildJsonObject {
                put("version", 1)
                put("kind", kind)
                put("body", body)
            }.toString().toByteArray(Charsets.UTF_8)
            require(bytes.size <= ENVELOPE_BYTES) { "Dispatch body exceeds fixed envelope size" }
            return ByteArray(ENVELOPE_BYTES) { if (it < bytes.size) bytes[it] else 32.toByte() }
        }
    }

    fun start() = synchronized(lock) {
        if (schedule?.isActive == true) return@synchronized
        schedule = scope.launch {
            while (isActive) {
                delay(intervalMillis)
                // Slow transport does not consume subsequent slots.
                scope.launch { tick() }
            }
        }
    }

    suspend fun submit(kind: String, body: JsonElement): ByteArray {
        require(kind != "dummy") { "Dummies are generated by scheduled slots" }
        val pending = Pending(encode(kind, body), CompletableDeferred())
        synchronized(lock) {
            check(schedule?.isActive == true) { "Cover traffic is not running" }
            check(queue.size < 64) { "Cover traffic queue is full" }
            queue.addLast(pending)
        }
        return try { pending.result.await() } finally {
            synchronized(lock) { queue.remove(pending) }
        }
    }

    internal suspend fun tick() {
        val next = synchronized(lock) {
            if (schedule?.isActive != true) return
            queue.pollFirst()
        }
        try {
            val bytes = next?.bytes ?: encode("dummy", Json.parseToJsonElement("{\"tx\":\"\"}"))
            val result = transport(bytes)
            next?.result?.complete(result)
        } catch (error: Exception) {
            next?.result?.completeExceptionally(error)
        }
    }

    fun stop() = synchronized(lock) {
        // Cancel only the schedule, not an already dispatched canonical write.
        // In-flight operations run in the supplied foreground session scope.
        schedule?.cancel()
        schedule = null
        while (queue.isNotEmpty()) queue.removeFirst().result.cancel()
    }
}
